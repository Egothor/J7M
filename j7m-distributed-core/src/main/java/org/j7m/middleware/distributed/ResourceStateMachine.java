package org.j7m.middleware.distributed;

import org.j7m.middleware.consensus.ReplicatedStateMachine;

/**
 * Deterministic replicated resource SPI. Implementations must not perform network, wall-clock or
 * random operations during apply; snapshots contain state, results, events and prepared locks.
 * Query synchronization must include all applies through the supplied quorum read index.
 */
public interface ResourceStateMachine extends ReplicatedStateMachine {
    /**
     * Queries a resource only after a quorum read barrier.
     * @param scope authorized scope
     * @param key resource key
     * @param readIndex committed index already applied by the hosting consensus node
     * @return value and version, or null when absent
     * @throws IllegalStateException if the barrier has not been applied
     */
    ReplicatedResources.Value queryAtReadIndex(String scope, String key, long readIndex);
}
