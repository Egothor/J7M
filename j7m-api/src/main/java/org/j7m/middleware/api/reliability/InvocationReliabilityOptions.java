package org.j7m.middleware.api.reliability;

import java.io.Serializable;
import java.time.Duration;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Typed reliability metadata carried through invocation options.
 *
 * <p>The record is immutable, serializable, and thread-safe. It serializes to
 * deterministic string metadata so transports remain vendor-neutral. Raw
 * payload values are never embedded in metadata generated by this type.</p>
 *
 * @param deliverySemantics delivery semantics
 * @param idempotencyKey optional idempotency key
 * @param dedupeKey optional dedupe key
 * @param orderingKey optional ordering key
 * @param durableOperationId optional durable operation id
 * @param fencingToken optional fencing token
 * @param monotonicEpoch optional epoch
 * @param causalContext optional causal context
 * @param correlationContext optional correlation context
 * @param replayPolicy replay policy
 * @param duplicateDetectionPolicy duplicate detection policy
 * @param backpressurePolicy backpressure policy
 * @param cancellationRequested cancellation propagation flag
 * @param maxPayloadBytes payload limit, or zero for unset
 * @param maxResultBytes result limit, or zero for unset
 * @param retryAfter retry-after metadata, or {@code null}
 */
public record InvocationReliabilityOptions(
        DeliverySemantics deliverySemantics,
        IdempotencyKey idempotencyKey,
        DedupeKey dedupeKey,
        OrderingKey orderingKey,
        DurableOperationId durableOperationId,
        FencingToken fencingToken,
        MonotonicEpoch monotonicEpoch,
        CausalContext causalContext,
        CorrelationContext correlationContext,
        ReplayPolicy replayPolicy,
        DuplicateDetectionPolicy duplicateDetectionPolicy,
        BackpressurePolicy backpressurePolicy,
        boolean cancellationRequested,
        long maxPayloadBytes,
        long maxResultBytes,
        Duration retryAfter) implements Serializable {

    /**
     * Prefix used for transport-neutral reliability metadata keys.
     */
    public static final String PREFIX = "j7m.reliability.";

    /**
     * Creates validated invocation reliability options.
     */
    public InvocationReliabilityOptions {
        deliverySemantics = deliverySemantics == null ? DeliverySemantics.atMostOnceBestEffort() : deliverySemantics;
        replayPolicy = replayPolicy == null ? ReplayPolicy.NO_REPLAY : replayPolicy;
        duplicateDetectionPolicy = duplicateDetectionPolicy == null ? DuplicateDetectionPolicy.DISABLED : duplicateDetectionPolicy;
        backpressurePolicy = backpressurePolicy == null ? BackpressurePolicy.REJECT_IMMEDIATELY : backpressurePolicy;
        if (maxPayloadBytes < 0L || maxResultBytes < 0L) {
            throw new IllegalArgumentException("payload and result limits must be non-negative");
        }
        if (retryAfter != null && retryAfter.isNegative()) {
            throw new IllegalArgumentException("retryAfter must be non-negative");
        }
    }

    /**
     * Returns default at-most-once reliability options.
     *
     * @return default options
     */
    public static InvocationReliabilityOptions defaults() {
        return new InvocationReliabilityOptions(DeliverySemantics.atMostOnceBestEffort(), null, null, null, null,
                null, null, null, null, ReplayPolicy.NO_REPLAY, DuplicateDetectionPolicy.DISABLED,
                BackpressurePolicy.REJECT_IMMEDIATELY, false, 0L, 0L, null);
    }

    /**
     * Decodes reliability options from invocation metadata.
     *
     * @param metadata metadata map
     * @return decoded options
     */
    public static InvocationReliabilityOptions fromMetadata(final Map<String, String> metadata) {
        Map<String, String> safe = metadata == null ? Map.of() : metadata;
        DeliverySemantics semantics = decodeDelivery(safe.get(PREFIX + "deliveryMode"));
        IdempotencyKey idempotencyKey = optional(safe, "idempotencyKey").isBlank() ? null : new IdempotencyKey(optional(safe, "idempotencyKey"));
        DedupeKey dedupeKey = optional(safe, "dedupeKey").isBlank() ? null : new DedupeKey(optional(safe, "dedupeKey"));
        OrderingKey orderingKey = optional(safe, "orderingKey").isBlank() ? null : new OrderingKey(optional(safe, "orderingKey"));
        DurableOperationId operationId = optional(safe, "durableOperationId").isBlank() ? null : new DurableOperationId(optional(safe, "durableOperationId"));
        FencingToken fencingToken = decodeFencing(safe);
        MonotonicEpoch epoch = decodeEpoch(safe);
        CausalContext causal = decodeCausal(safe);
        CorrelationContext correlation = decodeCorrelation(safe);
        ReplayPolicy replay = enumValue(ReplayPolicy.class, safe.get(PREFIX + "replayPolicy"), ReplayPolicy.NO_REPLAY);
        DuplicateDetectionPolicy duplicate = enumValue(DuplicateDetectionPolicy.class, safe.get(PREFIX + "duplicateDetectionPolicy"), DuplicateDetectionPolicy.DISABLED);
        BackpressurePolicy backpressure = enumValue(BackpressurePolicy.class, safe.get(PREFIX + "backpressurePolicy"), BackpressurePolicy.REJECT_IMMEDIATELY);
        boolean cancelled = Boolean.parseBoolean(safe.getOrDefault(PREFIX + "cancellationRequested", "false"));
        long payloadLimit = parseLong(safe.get(PREFIX + "maxPayloadBytes"));
        long resultLimit = parseLong(safe.get(PREFIX + "maxResultBytes"));
        long retryAfterMillis = parseLong(safe.get(PREFIX + "retryAfterMillis"));
        Duration retryAfter = retryAfterMillis == 0L ? null : Duration.ofMillis(retryAfterMillis);
        return new InvocationReliabilityOptions(semantics, idempotencyKey, dedupeKey, orderingKey, operationId,
                fencingToken, epoch, causal, correlation, replay, duplicate, backpressure, cancelled,
                payloadLimit, resultLimit, retryAfter);
    }

    /**
     * Encodes these options as transport-neutral metadata.
     *
     * @return metadata map
     */
    public Map<String, String> toMetadata() {
        Map<String, String> metadata = new LinkedHashMap<>();
        metadata.put(PREFIX + "deliveryMode", this.deliverySemantics.mode().name());
        metadata.put(PREFIX + "retrySafe", Boolean.toString(this.deliverySemantics.retrySafe()));
        metadata.put(PREFIX + "effectivelyOncePattern", Boolean.toString(this.deliverySemantics.effectivelyOncePattern()));
        put(metadata, "idempotencyKey", this.idempotencyKey == null ? "" : this.idempotencyKey.value());
        put(metadata, "dedupeKey", this.dedupeKey == null ? "" : this.dedupeKey.value());
        put(metadata, "orderingKey", this.orderingKey == null ? "" : this.orderingKey.value());
        put(metadata, "durableOperationId", this.durableOperationId == null ? "" : this.durableOperationId.value());
        if (this.fencingToken != null) {
            put(metadata, "fencingAuthority", this.fencingToken.authority());
            put(metadata, "fencingScope", this.fencingToken.scope());
            put(metadata, "fencingValue", Long.toString(this.fencingToken.value()));
        }
        if (this.monotonicEpoch != null) {
            put(metadata, "epochAuthority", this.monotonicEpoch.authority());
            put(metadata, "epochScope", this.monotonicEpoch.scope());
            put(metadata, "epochValue", Long.toString(this.monotonicEpoch.value()));
        }
        if (this.causalContext != null) {
            put(metadata, "causalTraceId", this.causalContext.traceId());
            put(metadata, "causalSpanId", this.causalContext.spanId());
            put(metadata, "causalParentSpanId", this.causalContext.parentSpanId());
        }
        if (this.correlationContext != null) {
            put(metadata, "correlationId", this.correlationContext.correlationId());
            put(metadata, "correlationInvocationId", this.correlationContext.invocationId());
            put(metadata, "correlationParentInvocationId", this.correlationContext.parentInvocationId());
        }
        metadata.put(PREFIX + "replayPolicy", this.replayPolicy.name());
        metadata.put(PREFIX + "duplicateDetectionPolicy", this.duplicateDetectionPolicy.name());
        metadata.put(PREFIX + "backpressurePolicy", this.backpressurePolicy.name());
        metadata.put(PREFIX + "cancellationRequested", Boolean.toString(this.cancellationRequested));
        if (this.maxPayloadBytes > 0L) {
            put(metadata, "maxPayloadBytes", Long.toString(this.maxPayloadBytes));
        }
        if (this.maxResultBytes > 0L) {
            put(metadata, "maxResultBytes", Long.toString(this.maxResultBytes));
        }
        if (this.retryAfter != null) {
            put(metadata, "retryAfterMillis", Long.toString(this.retryAfter.toMillis()));
        }
        return Map.copyOf(metadata);
    }

    /**
     * Merges these options into existing metadata.
     *
     * @param metadata existing metadata
     * @return merged metadata
     */
    public Map<String, String> mergeInto(final Map<String, String> metadata) {
        Map<String, String> merged = new LinkedHashMap<>(metadata == null ? Map.of() : metadata);
        merged.putAll(this.toMetadata());
        return Map.copyOf(merged);
    }

    private static String optional(final Map<String, String> metadata, final String name) {
        return metadata.getOrDefault(PREFIX + name, "");
    }

    private static void put(final Map<String, String> metadata, final String name, final String value) {
        if (value != null && !value.isBlank()) {
            metadata.put(PREFIX + name, value);
        }
    }

    private static DeliverySemantics decodeDelivery(final String mode) {
        DeliveryMode deliveryMode = enumValue(DeliveryMode.class, mode, DeliveryMode.AT_MOST_ONCE_BEST_EFFORT);
        if (deliveryMode == DeliveryMode.AT_LEAST_ONCE_RETRYABLE) {
            return DeliverySemantics.atLeastOnceRetryable();
        }
        if (deliveryMode == DeliveryMode.EFFECTIVELY_ONCE_PATTERN) {
            return DeliverySemantics.effectivelyOncePatternSupport();
        }
        if (deliveryMode == DeliveryMode.UNSUPPORTED_EXACTLY_ONCE) {
            return DeliverySemantics.unsupportedExactlyOnce();
        }
        return DeliverySemantics.atMostOnceBestEffort();
    }

    private static FencingToken decodeFencing(final Map<String, String> metadata) {
        String authority = optional(metadata, "fencingAuthority");
        String scope = optional(metadata, "fencingScope");
        long value = parseLong(metadata.get(PREFIX + "fencingValue"));
        return authority.isBlank() && scope.isBlank() && value == 0L ? null : new FencingToken(authority, scope, value);
    }

    private static MonotonicEpoch decodeEpoch(final Map<String, String> metadata) {
        String authority = optional(metadata, "epochAuthority");
        String scope = optional(metadata, "epochScope");
        long value = parseLong(metadata.get(PREFIX + "epochValue"));
        return authority.isBlank() && scope.isBlank() && value == 0L ? null : new MonotonicEpoch(authority, scope, value);
    }

    private static CausalContext decodeCausal(final Map<String, String> metadata) {
        String trace = optional(metadata, "causalTraceId");
        String span = optional(metadata, "causalSpanId");
        String parent = optional(metadata, "causalParentSpanId");
        return trace.isBlank() && span.isBlank() ? null : new CausalContext(trace, span, parent);
    }

    private static CorrelationContext decodeCorrelation(final Map<String, String> metadata) {
        String correlation = optional(metadata, "correlationId");
        String invocation = optional(metadata, "correlationInvocationId");
        String parent = optional(metadata, "correlationParentInvocationId");
        return correlation.isBlank() && invocation.isBlank() ? null : new CorrelationContext(correlation, invocation, parent);
    }

    private static long parseLong(final String value) {
        if (value == null || value.isBlank()) {
            return 0L;
        }
        try {
            long parsed = Long.parseLong(value);
            return Math.max(0L, parsed);
        } catch (NumberFormatException exception) {
            return 0L;
        }
    }

    private static <E extends Enum<E>> E enumValue(final Class<E> type, final String value, final E fallback) {
        if (value == null || value.isBlank()) {
            return fallback;
        }
        try {
            return Enum.valueOf(type, value);
        } catch (IllegalArgumentException exception) {
            return fallback;
        }
    }
}
