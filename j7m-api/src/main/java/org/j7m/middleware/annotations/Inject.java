package org.j7m.middleware.annotations;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Requests J7M-native dependency injection.
 *
 * <p>When placed on a constructor, the application platform resolves all
 * parameters from the application-scoped capability registry. When placed on a
 * field, the field is injected only if JPMS access permits reflective write
 * access. Missing or ambiguous dependencies fail activation with a stable
 * middleware error code and safe diagnostics.</p>
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target({ElementType.CONSTRUCTOR, ElementType.FIELD, ElementType.PARAMETER})
public @interface Inject {
    /**
     * Returns the explicit binding refresh mode; legacy injectors retain their existing behavior.
     * @return NEVER unless a managed host supplies a dynamic binding adapter
     */
    BindingRefresh refresh() default BindingRefresh.NEVER;
    /**
     * Returns the host-owned named binding policy.
     * @return default policy identifier
     */
    String policy() default "default";
}

