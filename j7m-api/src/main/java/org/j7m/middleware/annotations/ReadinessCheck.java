package org.j7m.middleware.annotations;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * <p>Managed-v1 hosting requires a finite public, non-static, zero-argument primitive-boolean
 * method on an ACTIVATION component. Legacy utility behavior is unchanged. A missing readiness
 * declaration is not proof that a managed deployment is ready for canary/rolling admission.</p>
 *
 * Marks a no-argument method that reports whether a component is ready to
 * accept traffic.
 *
 * <p>Readiness is separate from health. A component may be healthy but not
 * ready while it is warming caches, recovering durable state, or waiting for
 * dependent services.</p>
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.METHOD)
public @interface ReadinessCheck {
}

