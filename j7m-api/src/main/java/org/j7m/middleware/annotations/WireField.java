package org.j7m.middleware.annotations;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Defines a stable numeric wire identity independent of the Java record component name.
 * Every schema component must declare this annotation. Primitive components must be required.
 * Optional scalar defaults are parsed and validated at compilation; absent defaults mean null.
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.RECORD_COMPONENT)
public @interface WireField {
    /**
     * Returns the declared contract value.
     * @return positive wire ID, represented as canonical decimal by the D00 codec
     */
    int id();
    /**
     * Returns the declared contract value.
     * @return whether null or absent values are rejected
     */
    boolean required() default true;
    /**
     * Returns the declared contract value.
     * @return whether defaultValue is explicitly provided; required fields cannot have defaults
     */
    boolean hasDefault() default false;
    /**
     * Returns the declared contract value.
     * @return scalar default text; byte arrays and nested schemas cannot have non-null defaults
     */
    String defaultValue() default "";
}
