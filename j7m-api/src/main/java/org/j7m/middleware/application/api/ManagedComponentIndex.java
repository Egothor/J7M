package org.j7m.middleware.application.api;

import java.util.List;

/**
 * Finite generated component metadata supplied explicitly or through a declared module service.
 * Loading an index never grants a host capability or selects a deployment profile. The runtime
 * validates its format and complete graph before constructing any product.
 */
public interface ManagedComponentIndex {
    /**
     * Returns the index format version supported by this definition.
     * @return version1 by default
     */
    default int formatVersion() { return 1; }
    /**
     * Returns immutable finite product plans for this index.
     * @return component and factory definitions
     */
    List<ManagedComponentDefinition<?>> components();
    /**
     * Returns full overload-preserving method metadata.
     * @return immutable method signatures, empty when none are declared
     */
    default List<ManagedMethod> methods() { return List.of(); }
}
